create or replace package body afd_markdown as
    function render_document(p_document clob) return clob is
        d json_object_t := json_object_t.parse(p_document);
        app_obj json_object_t;
        pages json_array_t;
        components json_array_t;
        page_obj json_object_t;
        n json_object_t;
        props json_object_t;
        refs json_array_t;
        sources json_array_t;
        src json_object_t;
        keys json_key_list;
        result clob;
        fence varchar2(32767);
        text_value clob;
        l_count number;
        function safe_text(p_text varchar2) return varchar2 is
        begin
            return replace(replace(replace(replace(replace(replace(replace(replace(
                p_text,'&','&amp;'),'<','&lt;'),'>','&gt;'),'[','\['),']','\]'),'*','\*'),'_','\_'),'#','\#');
        end;
        procedure add(p_text clob) is
        begin
            if p_text is not null then dbms_lob.append(result,p_text); end if;
        end;
        procedure line(p_text varchar2 default null) is
        begin
            add(to_clob(p_text || chr(10)));
        end;
        procedure code(p_text clob,p_language varchar2 default 'text') is
        begin
            fence := '```';
            while dbms_lob.instr(p_text,fence)>0 loop
                fence := fence || '`';
                if length(fence)>10000 then raise_application_error(-20005,'Unsupported Markdown fence length.'); end if;
            end loop;
            line(fence || case when p_language in ('sql','plsql','json','text','javascript','html') then p_language else 'text' end);
            add(p_text);
            line;
            line(fence);
            line;
        end;
        procedure component_section(p_node json_object_t) is
            v json_element_t;
            value_text clob;
            skip_source boolean;
        begin
            n := p_node;
            line('### ' || safe_text(n.get_string('name')));
            line;
            line('Type: ' || safe_text(n.get_string('family')) || ' · Key: ' || safe_text(n.get_string('key')));
            line;
            line('Source representation: ' || safe_text(n.get_string('sourceKind')) || '.');
            line;
            if n.get_string('comment') is not null then
                line(safe_text(n.get_string('comment')));
                line;
            else
                line('No developer comment recorded.');
                line;
            end if;
            line('#### Definition');
            line;
            props := n.get_object('properties');
            sources := n.get_array('sources');
            keys := props.get_keys;
            -- Keys retain the fixed collector projection order; no timestamp sorting.
            for k in 1 .. keys.count loop
                skip_source := false;
                for s in 0 .. sources.get_size - 1 loop
                    src := treat(sources.get(s) as json_object_t);
                    if keys(k) = src.get_string('column') then skip_source := true; end if;
                end loop;
                v := props.get(keys(k));
                if not v.is_null and not skip_source then
                    line('**' || safe_text(keys(k)) || '**');
                    line;
                    if v.is_string then value_text := props.get_clob(keys(k)); else value_text := v.to_clob; end if;
                    code(value_text,case when v.is_object or v.is_array then 'json' else 'text' end);
                end if;
            end loop;
            for s in 0 .. sources.get_size - 1 loop
                src := treat(sources.get(s) as json_object_t);
                line('#### ' || safe_text(src.get_string('column')));
                line;
                code(src.get_clob('text'),src.get_string('language'));
            end loop;
            line('#### Provenance');
            line;
            code(n.get_object('origin').to_clob,'json');
            refs := n.get_array('references');
            if refs.get_size > 0 then
                line('#### Declared references');
                line;
                code(refs.to_clob,'json');
            end if;
        end;
    begin
        if d.get_string('schemaVersion') != '1.0' then raise_application_error(-20006,'Unsupported documentation schema.'); end if;
        dbms_lob.createtemporary(result,true);
        app_obj := d.get_object('application');
        pages := d.get_array('pages');
        components := d.get_array('components');
        line('# ' || safe_text(app_obj.get_string('APPLICATION_NAME')));
        line;
        line('Generated by APEX Application Docs ' || safe_text(d.get_string('collectorVersion')) || '.');
        line;
        line('APEX runtime: ' || safe_text(d.get_string('apexVersion')) || ' · Captured at: ' || safe_text(d.get_string('capturedAtUtc')));
        line;
        line('This document describes declared configuration. It does not prove runtime execution or business intent.');
        line;
        line('## Contents');
        line;
        line('- [Application](#application)');
        for i in 0 .. pages.get_size - 1 loop
            page_obj := treat(pages.get(i) as json_object_t);
            line('- [Page ' || page_obj.get_number('pageId') || '](#page-' || page_obj.get_number('pageId') || ') — ' || safe_text(page_obj.get_string('name')));
        end loop;
        line('- [Shared authorizations](#shared-authorizations)');
        line('- [Coverage and limitations](#coverage-and-limitations)');
        line;
        line('## Application');
        line;
        code(app_obj.to_clob,'json');
        for i in 0 .. pages.get_size - 1 loop
            page_obj := treat(pages.get(i) as json_object_t);
            line('## Page ' || page_obj.get_number('pageId'));
            line;
            line(safe_text(page_obj.get_string('name')));
            line;
            code(page_obj.to_clob,'json');
            l_count := 0;
            for j in 0 .. components.get_size - 1 loop
                n := treat(components.get(j) as json_object_t);
                if n.get_number('pageId') = page_obj.get_number('pageId') then
                    component_section(n);
                    l_count := l_count + 1;
                end if;
            end loop;
            if l_count = 0 then line('No components in the supported families on this page.'); line; end if;
        end loop;
        line('## Shared authorizations');
        line;
        l_count := 0;
        for j in 0 .. components.get_size - 1 loop
            n := treat(components.get(j) as json_object_t);
            if n.get_string('family') = 'authorization' then component_section(n); l_count := l_count + 1; end if;
        end loop;
        if l_count = 0 then line('No application authorization schemes recorded.'); line; end if;
        line('## Coverage and limitations');
        line;
        code(d.get_array('coverage').to_clob,'json');
        line(safe_text(d.get_string('limitations')));
        return result;
    end;
end afd_markdown;
/
